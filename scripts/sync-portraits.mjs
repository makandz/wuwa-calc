import { createHash } from "node:crypto";
import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const root = new URL("../", import.meta.url);
const endpoint = "https://api-v2.encore.moe/api/en/character";
const response = await fetch(endpoint);
if (!response.ok) throw new Error(`Character API: ${response.status}`);
const { roleList } = await response.json();
const roverIcon = roleList.find((entry) => entry.Id === 1501)?.RoleHeadIcon;
const names = new Set();
for (const element of await readdir(new URL("src/resonators/", root), { withFileTypes: true })) {
  if (!element.isDirectory()) continue;
  const directory = new URL(`src/resonators/${element.name}/`, root);
  for (const file of await readdir(directory)) {
    if (!file.endsWith(".ts")) continue;
    const source = await readFile(new URL(file, directory), "utf8");
    const match = /new Resonator\(\{\s*(?:id:\s*\d+,\s*)?name:\s*"([^"]+)"/.exec(source);
    if (match) names.add(match[1]);
  }
}

if (!names.size) throw new Error("No resonators found");

const portraits = {};
const downloaded = new Map();
const directory = new URL("assets/portraits/", root);
await mkdir(directory, { recursive: true });
for (const name of [...names].sort()) {
  const apiName = name === "Xuanling" ? "Yangyang: Xuanling"
    : name.endsWith(" Rover") ? `Rover: ${name.slice(0, -6)}` : name;
  const role = roleList.find((entry) => entry.Name === apiName
    && (!name.endsWith(" Rover") || entry.RoleHeadIcon === roverIcon));
  // Upstream includes Lily before Encore publishes her portrait.
  if (!role?.RoleHeadIcon && name === "Lily") {
    console.warn("Skipping Lily: Encore has no portrait yet");
    continue;
  }
  if (!role?.RoleHeadIcon) throw new Error(`No portrait for ${name}`);
  let filename = downloaded.get(role.RoleHeadIcon);
  if (!filename) {
    const image = await fetch(role.RoleHeadIcon);
    if (!image.ok) throw new Error(`Portrait for ${name}: ${image.status}`);
    const data = Buffer.from(await image.arrayBuffer());
    if (data.toString("ascii", 0, 4) !== "RIFF" || data.toString("ascii", 8, 12) !== "WEBP") {
      throw new Error(`Invalid WebP for ${name}`);
    }
    filename = `${createHash("sha256").update(data).digest("hex").slice(0, 16)}.webp`;
    await writeFile(new URL(filename, directory), data);
    downloaded.set(role.RoleHeadIcon, filename);
  }
  portraits[name] = filename;
}

const manifest = "// Generated by scripts/sync-portraits.mjs from Encore's RoleHeadIcon field.\n"
  + `export const PORTRAITS: Readonly<Record<string, string>> = ${JSON.stringify(portraits, null, 2)};\n`;
await writeFile(new URL("src/page/portrait-assets.ts", root), manifest);
console.log(`Saved ${downloaded.size} images for ${names.size} characters in ${fileURLToPath(directory)}`);
